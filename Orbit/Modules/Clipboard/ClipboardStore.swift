import AppKit
import CryptoKit
import Observation

/// Watches the general pasteboard and keeps a local, private history.
@MainActor @Observable
final class ClipboardStore {
    static let shared = ClipboardStore()
    nonisolated static let dir = Storage.dir("Clips")

    private(set) var items: [ClipItem] = []
    private(set) var paused = false

    private var lastChange = NSPasteboard.general.changeCount
    private var ownChange: Int?
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private let imageCache = NSCache<NSString, NSImage>()

    /// nspasteboard.org markers — never record these.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    private init() {
        items = Storage.load([ClipItem].self, from: "clipboard.json") ?? []
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardStore.shared.poll() }
        }
        timer?.tolerance = 0.2
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ownChange == pb.changeCount { return }
        refreshPause()
        guard !paused else { return }

        let front = NSWorkspace.shared.frontmostApplication
        let ignored = Pref.defaults.stringArray(forKey: Pref.ignoredApps) ?? []
        if let id = front?.bundleIdentifier, ignored.contains(id) { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        guard var item = read(pb) else { return }
        item.appBundleID = front?.bundleIdentifier
        item.appName = front?.localizedName
        insert(item)
    }

    private func read(_ pb: NSPasteboard) -> ClipItem? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(kind: .file, filePaths: paths, signature: hash(paths.joined(separator: "|")))
        }

        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), let image = NSImage(data: data),
           pb.string(forType: .string) == nil {
            guard let png = image.pngData else { return nil }
            let sig = hash(png)
            if let existing = items.first(where: { $0.signature == sig }) { return existing }
            let name = "\(UUID().uuidString).png"
            try? png.write(to: Self.dir.appendingPathComponent(name))
            let rep = image.representations.first
            let size = CGSize(width: rep?.pixelsWide ?? Int(image.size.width), height: rep?.pixelsHigh ?? Int(image.size.height))
            var item = ClipItem(kind: .image, imageFile: name, imageSize: size, signature: sig)
            recognize(&item, image: image)
            return item
        }

        guard let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        var item = ClipItem(kind: classify(string), text: string, signature: hash(string))
        if let rtf = pb.data(forType: .rtf), rtf.count < 2_000_000 {
            let name = "\(UUID().uuidString).rtf"
            try? rtf.write(to: Self.dir.appendingPathComponent(name))
            item.rtfFile = name
        }
        return item
    }

    private func classify(_ s: String) -> ClipItem.Kind {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.range(of: #"^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$"#, options: .regularExpression) != nil, t.hasPrefix("#") { return .color }
        if !t.contains(" "), !t.contains("\n"), let url = URL(string: t), let scheme = url.scheme,
           ["http", "https"].contains(scheme), url.host() != nil { return .link }
        return .text
    }

    private func recognize(_ item: inout ClipItem, image: NSImage) {
        let id = item.id
        guard let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
        Task {
            let text = try? await OCR.recognize(cg)
            guard let text, !text.isEmpty, let i = items.firstIndex(where: { $0.id == id }) else { return }
            items[i].ocrText = text
            scheduleSave()
        }
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if let i = items.firstIndex(where: { $0.signature == item.signature }) {
            // Re-copied: move to the top, keep pin state and stored files.
            let old = items.remove(at: i)
            item.id = old.id
            item.pinned = old.pinned
            item.ocrText = item.ocrText ?? old.ocrText
            if item.imageFile == nil { item.imageFile = old.imageFile }
            if item.rtfFile == nil { item.rtfFile = old.rtfFile } else if old.rtfFile != item.rtfFile { removeFiles(of: old, keepImage: true) }
        }
        item.date = Date()
        items.insert(item, at: 0)
        trim()
        scheduleSave()
    }

    private func trim() {
        let limit = max(20, Pref.defaults.integer(forKey: Pref.historyLimit))
        var unpinned = 0
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            if unpinned > limit { removeFiles(of: item); return true }
            return false
        }
    }

    // MARK: Actions

    func copy(_ item: ClipItem, plain: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text, .link, .color:
            if !plain, let url = item.rtfURL, let rtf = try? Data(contentsOf: url) { pb.setData(rtf, forType: .rtf) }
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if plain, let ocr = item.ocrText { pb.setString(ocr, forType: .string) }
            else if let url = item.imageURL, let data = try? Data(contentsOf: url) { pb.setData(data, forType: .png) }
        case .file:
            pb.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        markOwnWrite()
        // Bump to top so the history reflects what's actually on the clipboard.
        if let i = items.firstIndex(of: item), i != 0 {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }
    }

    /// Records our own pasteboard writes so the monitor doesn't re-add them.
    func markOwnWrite() {
        ownChange = NSPasteboard.general.changeCount
        lastChange = ownChange!
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeFiles(of: item)
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        for item in items where !(keepPinned && item.pinned) { removeFiles(of: item) }
        items.removeAll { !(keepPinned && $0.pinned) }
        scheduleSave()
    }

    func pause(for interval: TimeInterval?) {
        let until = interval.map { Date().addingTimeInterval($0) } ?? .distantFuture
        Pref.defaults.set(until.timeIntervalSince1970, forKey: Pref.pausedUntil)
        refreshPause()
    }

    func resume() {
        Pref.defaults.removeObject(forKey: Pref.pausedUntil)
        refreshPause()
    }

    private func refreshPause() {
        let until = Pref.defaults.double(forKey: Pref.pausedUntil)
        paused = until > Date().timeIntervalSince1970
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let url = item.imageURL else { return nil }
        if let cached = imageCache.object(forKey: url.path as NSString) { return cached }
        guard let image = NSImage(contentsOf: url) else { return nil }
        imageCache.setObject(image, forKey: url.path as NSString)
        return image
    }

    func search(_ query: String, kind: ClipItem.Kind? = nil, pinnedOnly: Bool = false) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        return items.filter { item in
            if pinnedOnly, !item.pinned { return false }
            if let kind, item.kind != kind { return false }
            return q.isEmpty || item.searchable.lowercased().contains(q)
        }
    }

    // MARK: Persistence

    private func removeFiles(of item: ClipItem, keepImage: Bool = false) {
        if !keepImage, let url = item.imageURL { try? FileManager.default.removeItem(at: url) }
        if let url = item.rtfURL { try? FileManager.default.removeItem(at: url) }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let snapshot = items
        let work = DispatchWorkItem { Storage.save(snapshot, to: "clipboard.json") }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    private func hash(_ string: String) -> String { hash(Data(string.utf8)) }
    private func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
